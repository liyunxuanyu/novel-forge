/**
 * 测试用的候选细纲构造器。
 *
 * ## 为什么需要它
 *
 * `forge_confirm_outline` 从 2026-10-11 起硬卡两个字段：`目标情绪` 与
 * `主角目标/关键选择`。判据不是我们拍脑袋定的，是 oh-story 的消融实验结论
 * （`references/workflow-outline.md` 第 21 行，见 `lib/outline.js` 的注释）：
 * **只补这两个字段，正文收益与补满全部字段不可区分**。
 *
 * 加这道闸门之后，十几个测试的旧夹具全部被拦——而它们被拦之后，
 * 后面整条链（备料→起草→审读→改稿→定稿）全部塌方，
 * 于是「改稿轮次上限」「字数闸门」「元信息隔离」这些**跟细纲字段毫无关系**的
 * 测试也跟着红。那不是新代码坏了，是夹具停留在旧格式。
 *
 * 修法是把这个形状集中到一处，而不是在十四个文件里各写一遍九个字段：
 * 一处改，将来字段变动只改这里。每份细纲只补自己关心的那几句约束。
 */

/**
 * 造一份能过确认的候选细纲。
 *
 * @param {{title?: string, constraints?: string[], extra?: string}} opts
 *   - `title`：章节标题，默认「雨夜」。
 *   - `constraints`：**这一份特有的约束行**（通常带〔硬〕〔软〕〔自由〕）。
 *     排到硬字段后面，所以约束仍然是最靠近作者意图的位置。
 *   - `extra`：整段追加文本（填小节用）。
 */
export function outlineFixture({ title = "雨夜", constraints = [], extra = "" } = {}) {
  const body = [
    `# 第一章 ${title}`,
    "",
    "- 核心事件：沈昭在雨夜里被逼着开口。",
    "- 字数目标：2800 字",
    "- 字数口径：visible_chars_v1",
    "- 单元ID/位置：L01-01；单元内第一拍，承担起势",
    // 这两条是确认闸门硬卡的。占位符同样不放过——写了 `[待补充]` 等于没写，
    // 而且比空着更坏：它看起来像填过了。
    "- 目标情绪：戒备 → 被迫承认自己在替人挡",
    "- 主角目标/关键选择：他要保住那份口供；必须选择当众开口而不是私下交人",
    "- 章首钩子：雨里那把伞先递过来，人还没开口",
    "- 爽点：无显性爽点，功能是让读者先站到他这边",
    "- 本章禁止提前释放：不揭露指使人；不解释口供的来路",
    ...constraints,
    "",
    "#### 内容概括（五段式）",
    "- 起因：雨夜有人找上门",
    "- 发展：对方要他闭嘴",
    "- 转折：他发现自己被架在火上",
    "- 高潮：当众开口",
    "- 结尾：雨停在天亮之前，他把伞还回去",
    "",
    "#### 情节安排（多线）",
    "- 主线推进：从被动躲到被迫开口",
    "- 辅线推进：无",
    "- 事件线：找人 → 对峙",
    "- 感情线：无显性，但关系从陌生变成互相欠一次",
    "- 逻辑线：被人架住 → 权衡 → 开口 → 欠下一次人情",
    "",
    "#### 人物关系和出场顺序",
    "- 出场顺序：沈昭、来人",
    "- 人物关系变化：戒备 → 被迫承认",
    "- 视角/信息差：读者知道有人在替他挡，沈昭不知道",
    "",
    "#### 情节细化",
    "| # | 情节点（谁做了什么） | 功能标签 | 执行边界（禁＋放） |",
    "|---|---|---|---|",
    "| 1 | 沈昭在雨里被堵住去路 | 铺垫 | 禁：不翻脸。放：允许他先问一句再沉默 |",
    "| 2 | 他当众说出第一个字 | 高潮 | 禁：不解释动机。放：允许他失态一次 |",
    "",
    "- 复沓锚句：无",
    "",
    "#### 结尾设定和钩子",
    "- 结尾设定：他把伞还回去，转身走了",
    "- 章尾钩子：下一个来的不是同一个人 — 具体内容，期待度：中；与下一章如何承接",
    ...(extra ? ["", extra] : []),
  ];
  return body.join("\n") + "\n";
}