/**
 * 写作执行六条。搬自 `roles/narrative-writer.md` 第 71-78 行。
 *
 * 其中「烈度反保守」一条与我们原来给模型的指令是**反的**：
 * 我们一路在压「克制、别过头」，它明写「宁过火不平淡」。
 * 悬疑推理也不该弱——该紧的地方要压过去，该给的爆点要给足。
 */
function renderCraft() {
  return [
    "## 三、怎么写",
    "",
    "- **开局**：接上一章最后的动作／台词／现场。**禁大段环境描写或背景复盘开场。**",
    "- **叙述姿态**：默认深度限知——锁死主视角此刻感知，不切他人内心、不提前剧透、",
    "  场景被他的情绪染色。〔硬〕或本书文风另有规定时照那个执行。",
    "- **场景推进**：进入处境，把有新信息的发生／感知／反应揉进同一镜头。",
    "  **不按维度凑段，不补反应尾巴。**核心戏展开，过场简写，收尾落钩子或情绪定格。",
    "  按新动作／物件／信息／对话断段。",
    "- **情绪执行**：优先用选择、台词、物件、后果落地，必要时直写。",
    "  身体细节只在承担伤势／失败／习惯／后果时才写，**不堆无功能小动作**。",
    "  **烈度反保守**：网文要强情绪——冲突前置、揭露要狠而具体、当众、有代价。",
    "  宁过火不平淡（以克制为卖点的题材除外）。",
    "- **对话**：推进剧情或揭示性格，带潜台词与信息控制。不要让角色替作者解释。",
    "- **收尾**：章尾落在动作／对话／悬念上。",
    "  **禁升华总结**（「他终于明白」「这一夜注定」）、**禁章末预告**（「他不知道的是」）。",
  ];
}

/**
 * 写手身份全文。
 *
 * @param {{genre?: string, styleBrief?: string}} opts
 */
export function renderWriterRole({ genre = "", styleBrief = "" } = {}) {
  // 注意必须**展开**：renderPriority/renderLaws/renderCraft 返回的都是数组，
  // 直接把数组塞进待 join 的数组里，内层会被 Array.toString() 用逗号连接，
  // 整份身份的换行全部消失，输出成一长串 `,,` 夹着的文字。
  // 真机上就这么印出来过——而且它看起来「有内容」，不报错，只是没法读。
  return [
    ...renderPriority(),
    "",
    ...renderLaws(),
    "",
    ...renderCraft(),
    "",
    // renderProseSpec 自带 `## 写作纪律` 一级标题，这里不再加一个，
    // 否则同一份文档里出现两个同名标题（改完上面那个展开 bug 才看得见）。
    renderProseSpec({ genre, styleBrief }),
  ].join("\n");
}

